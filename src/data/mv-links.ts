function mvLinkKey(group: string, workTitle: string): string {
  return `${group.trim()}\u0000${workTitle.trim()}`;
}

const mvUrlByGroupAndWork = new Map<string, string | null>(
  mvLinks.map((link) => [mvLinkKey(link.group, link.workTitle), link.mvUrl]),
);

/** グループ名 + 作品名から公式 MV 直リンクを引く。未登録・不明は null。 */
export function lookupMvUrl(
  group: string,
  workTitle: string,
): string | null {
  if (!group.trim() || !workTitle.trim()) return null;
  if (!mvUrlByGroupAndWork.has(mvLinkKey(group, workTitle))) return null;
  return mvUrlByGroupAndWork.get(mvLinkKey(group, workTitle)) ?? null;
}
